// Raise (RZC) CAN box: its own one-byte codes. Filled in once read from com.qf.vehicle.
export const RAISE = {};

/**
 * One warning from the app, { code, proto: 'psa' | 'raise', detail? }, as text, level and zone.
 * A code nobody has named yet still shows, with its number, so it can be looked up.
 */
export function describe(w) {
  const table = w.proto === 'raise' ? RAISE : PSA;
  const hit = table[w.code];
  if (hit) return { text: hit[0], level: hit[1], zone: hit[2], known: true };
  const hex = '0x' + w.code.toString(16).toUpperCase().padStart(w.proto === 'raise' ? 2 : 4, '0');
  return { text: 'Alerte du véhicule n° ' + hex, level: 'service', zone: null, known: false };
}
